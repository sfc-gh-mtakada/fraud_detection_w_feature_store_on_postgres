USE ROLE ACCOUNTADMIN;

-- Roles: producer manages feature views, consumer reads online features
CREATE ROLE IF NOT EXISTS FRAUD_FS_PRODUCER;
CREATE ROLE IF NOT EXISTS FRAUD_FS_CONSUMER;
GRANT ROLE FRAUD_FS_CONSUMER TO ROLE FRAUD_FS_PRODUCER;
GRANT ROLE FRAUD_FS_PRODUCER TO ROLE SYSADMIN;
GRANT ROLE FRAUD_FS_PRODUCER TO USER ADMIN;

-- Compute
CREATE WAREHOUSE IF NOT EXISTS FRAUD_WH
  WAREHOUSE_SIZE = 'MEDIUM' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE;
CREATE COMPUTE POOL IF NOT EXISTS FRAUD_POOL
  MIN_NODES = 1 MAX_NODES = 2 INSTANCE_FAMILY = CPU_X64_S AUTO_SUSPEND_SECS = 600;

-- Database layout
CREATE DATABASE IF NOT EXISTS FRAUD_DEMO;
CREATE SCHEMA IF NOT EXISTS FRAUD_DEMO.RAW;        -- landing zone (bulk + Snowpipe Streaming)
CREATE SCHEMA IF NOT EXISTS FRAUD_DEMO.FS;         -- feature store objects
CREATE SCHEMA IF NOT EXISTS FRAUD_DEMO.ML;         -- models, training sets

GRANT USAGE ON WAREHOUSE FRAUD_WH TO ROLE FRAUD_FS_CONSUMER;
GRANT USAGE, MONITOR ON COMPUTE POOL FRAUD_POOL TO ROLE FRAUD_FS_PRODUCER;
GRANT OWNERSHIP ON DATABASE FRAUD_DEMO TO ROLE FRAUD_FS_PRODUCER COPY CURRENT GRANTS;
GRANT OWNERSHIP ON ALL SCHEMAS IN DATABASE FRAUD_DEMO TO ROLE FRAUD_FS_PRODUCER COPY CURRENT GRANTS;
GRANT USAGE ON DATABASE FRAUD_DEMO TO ROLE FRAUD_FS_CONSUMER;
GRANT USAGE ON ALL SCHEMAS IN DATABASE FRAUD_DEMO TO ROLE FRAUD_FS_CONSUMER;
-- create_online_service() only needs CREATE SCHEMA on the FS database (covered by ownership).
-- Stream FV backfill and FV refresh run as tasks owned by the producer role.
GRANT EXECUTE TASK, EXECUTE MANAGED TASK ON ACCOUNT TO ROLE FRAUD_FS_PRODUCER;
-- ML Job falls back to pip-installing snowflake-ml-python>=2.5 when Runtime 3.0 isn't rolled out yet
GRANT USAGE ON INTEGRATION PYPI_ACCESS_INTEGRATION TO ROLE FRAUD_FS_PRODUCER;

