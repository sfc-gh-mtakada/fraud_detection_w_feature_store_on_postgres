USE ROLE FRAUD_FS_PRODUCER;
USE WAREHOUSE FRAUD_WH;

-- Master data
CREATE OR REPLACE TABLE FRAUD_DEMO.RAW.CARDS (
  CARD_ID       VARCHAR,
  CUSTOMER_SEG  VARCHAR,     -- MASS / AFFLUENT / CORPORATE
  ISSUED_AT     DATE,
  HOME_PREF     VARCHAR      -- home prefecture
);

CREATE OR REPLACE TABLE FRAUD_DEMO.RAW.ACCEPTORS (
  ACCEPTOR_ID   VARCHAR,
  MCC           VARCHAR,     -- merchant category code
  MERCHANT_NAME VARCHAR,
  PREF          VARCHAR
);

-- Transaction table: target of both the historical bulk load and Snowpipe Streaming v2
CREATE OR REPLACE TABLE FRAUD_DEMO.RAW.CARD_TRANSACTIONS (
  TXN_ID        VARCHAR,
  CARD_ID       VARCHAR,
  ACCEPTOR_ID   VARCHAR,
  TS            TIMESTAMP_NTZ,   -- always UTC
  AMOUNT        NUMBER(12,0),    -- JPY
  ENTRY_MODE    VARCHAR,         -- CONTACTLESS / CHIP / ECOM / MAGSTRIPE
  MCC           VARCHAR,
  DEVICE_ID     VARCHAR,
  IS_FRAUD      BOOLEAN,         -- label (known later in reality)
  SOURCE        VARCHAR          -- HISTORY / STREAM
);

-- Snowpipe Streaming v2 (high-performance) pipe used by 04_simulator.py
CREATE OR REPLACE PIPE FRAUD_DEMO.RAW.CARD_TRANSACTIONS_PIPE AS
  COPY INTO FRAUD_DEMO.RAW.CARD_TRANSACTIONS
  FROM TABLE (DATA_SOURCE(TYPE => 'STREAMING'))
  MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;

-- Authorization decisions written back by the app (also mirrored into Postgres OLTP)
CREATE OR REPLACE TABLE FRAUD_DEMO.RAW.AUTH_DECISIONS (
  TXN_ID VARCHAR, CARD_ID VARCHAR, ACCEPTOR_ID VARCHAR, TS TIMESTAMP_NTZ,
  AMOUNT NUMBER(12,0), SCORE FLOAT, DECISION VARCHAR, LATENCY_MS FLOAT,
  FEATURES VARIANT
);
